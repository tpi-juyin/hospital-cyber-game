test('public endpoint isolates host controls; host requires private cookie and exact origin', async t => {
  const server = await startServers(); t.after(() => server.stop());
  assert.equal((await fetch(server.playerUrl + '/api/health')).status, 200);
  for (const path of ['/host.html', '/../package.json', '/scripts/launch.mjs', '/.runtime/instance.json']) assert.equal((await fetch(server.playerUrl + path)).status, 404);
  assert.equal((await fetch(server.playerUrl + '/api/host/state')).status, 403);
  assert.equal((await fetch(server.playerUrl)).status, 200);
  const host = new URL(server.hostUrl).origin;
  assert.equal((await fetch(host + '/api/host/state')).status, 403);
  const login = await fetch(server.hostUrl, { redirect: 'manual' }); assert.equal(login.status, 303);
  const cookie = login.headers.get('set-cookie')!.split(';')[0];
  const response = await fetch(host + '/api/host/state', { headers: { Cookie: cookie } }); assert.equal(response.status, 200); assert.equal((await response.json()).lobby.capacity, 30);
  const post = (origin: string) => fetch(host + '/api/host/action', { method: 'POST', headers: { Cookie: cookie, Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ kind: 'duration', value: 90 }) });
  assert.equal((await post('https://evil.example')).status, 403); assert.equal((await post(host)).status, 200); assert.equal(server.engine.defaultDuration, 90);
  const forgedHostStatus = await new Promise<number | undefined>((resolve, reject) => { const req = get(host, { headers: { Host: 'evil.example', Cookie: cookie } }, res => { res.resume(); resolve(res.statusCode); }); req.on('error', reject); });
  assert.equal(forgedHostStatus, 403);
});
test('real WebSocket sessions create isolated rooms, reject full joins, and resume with same token', async t => {
  const server = await startServers(); t.after(() => server.stop()); const clients: Socket[] = []; t.after(() => clients.forEach(s => s.close()));
  const a = await connect(server.playerUrl), d = await connect(server.playerUrl), c = await connect(server.playerUrl); clients.push(a.socket, d.socket, c.socket);
  assert.ok((await send(a.socket, { kind: 'name', name: '<script>alert(1)</script>' })).ok === false);
  assert.ok((await send(a.socket, { kind: 'create', mode: 'duo', role: 'attack', duration: 30 })).ok);
  const room = server.engine.playerView(a.session.id)!;
  assert.ok((await send(d.socket, { kind: 'join', code: room.code })).ok);
  assert.equal((await send(c.socket, { kind: 'join', code: room.code })).code, 'FULL');
  assert.ok((await send(c.socket, { kind: 'create', mode: 'solo', role: 'defense', duration: 60 })).ok);
  assert.notEqual(server.engine.playerView(c.session.id)!.id, room.id);
  const observed: RoomView[] = []; c.socket.on('room', r => { if (r) observed.push(r); });
  await new Promise(r => setTimeout(r, 250)); assert.ok(observed.length > 0); assert.ok(observed.every(r => r.id !== room.id));
  assert.ok(!JSON.stringify(room).includes(a.session.token));
  d.socket.disconnect(); await new Promise(r => setTimeout(r, 30)); const resumed = await connect(server.playerUrl, d.session.token); clients.push(resumed.socket); assert.equal(resumed.session.id, d.session.id); assert.equal(resumed.session.roomId, room.id);
  const replacement = await connect(server.playerUrl, a.session.token); clients.push(replacement.socket); await new Promise(r => setTimeout(r, 30)); assert.equal(a.socket.connected, false); assert.equal(server.engine.players.get(a.session.id)!.connected, true);
});
