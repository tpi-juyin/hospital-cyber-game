test('only the authenticated host can enable surrender, broadcasts it and receives the resulting win', async t => {
  const server = await startServers(); t.after(() => server.stop());
  const client = await connect(server.playerUrl); t.after(() => client.socket.close());
  const host = new URL(server.hostUrl).origin;
  const login = await fetch(server.hostUrl, { redirect: 'manual' }), cookie = login.headers.get('set-cookie')!.split(';')[0];
  const post = (value: unknown, authenticated = true, origin = host) => fetch(host + '/api/host/action', { method: 'POST', headers: { ...(authenticated ? { Cookie: cookie } : {}), Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ kind: 'allow-surrender', value }) });
  assert.equal((await fetch(server.playerUrl + '/api/health').then(r => r.json())).version, GAME_VERSION);
  assert.equal((await post(true, false)).status, 403); assert.equal((await post(true, true, 'https://elsewhere.example')).status, 403);
  assert.equal((await post('true')).status, 400); assert.equal(server.engine.allowSurrender, false);
  const updated = new Promise<LobbyView>(resolve => { const watch = (lobby: LobbyView) => { if (lobby.allowSurrender) { client.socket.off('lobby', watch); resolve(lobby); } }; client.socket.on('lobby', watch); });
  assert.equal((await post(true)).status, 200);
  assert.equal((await updated).allowSurrender, true);
  assert.ok((await send(client.socket, { kind: 'create', mode: 'solo', role: 'defense', duration: 30 })).ok);
  assert.ok((await send(client.socket, { kind: 'ready', ready: true })).ok);
  // Move this test room across countdown without waiting three real seconds.
  const room = server.engine.rooms.get(server.engine.playerView(client.session.id)!.id)!;
  room.deadline = performance.now(); server.engine.advance();
  assert.ok((await send(client.socket, { kind: 'surrender', roundId: room.roundId, seq: 1 })).ok);
  const state = await fetch(host + '/api/host/state', { headers: { Cookie: cookie } }).then(r => r.json());
  assert.equal(state.lobby.version, GAME_VERSION); assert.equal(state.rooms[0].winner, 'attack'); assert.match(state.rooms[0].reason, /投降/);
  assert.equal((await post(false)).status, 200); assert.equal(server.engine.allowSurrender, false);
});

test('ultimate mode requires authenticated host access and fourth-move requests remain scoped to their own round', async t => {
  const server = await startServers(); t.after(() => server.stop());
  const client = await connect(server.playerUrl); t.after(() => client.socket.close());
  const host = new URL(server.hostUrl).origin, login = await fetch(server.hostUrl, { redirect: 'manual' });
  const cookie = login.headers.get('set-cookie')!.split(';')[0];
  const post = (value: unknown, authenticated = true, origin = host) => fetch(host + '/api/host/action', { method: 'POST', headers: { ...(authenticated ? { Cookie: cookie } : {}), Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ kind: 'ultimate-mode', value }) });
  assert.equal((await post(true, false)).status, 403); assert.equal((await post(true, true, 'https://elsewhere.example')).status, 403);
  assert.equal((await post('true')).status, 400); assert.equal(server.engine.lobby().ultimateMode, true);
  assert.equal((await post(false)).status, 200); assert.equal(server.engine.lobby().ultimateMode, false);
  const updated = new Promise<LobbyView>(resolve => { const watch = (l: LobbyView) => { if (l.ultimateMode) { client.socket.off('lobby', watch); resolve(l); } }; client.socket.on('lobby', watch); });
  assert.equal((await post(true)).status, 200); assert.equal((await updated).ultimateMode, true);
  await send(client.socket, { kind: 'create', mode: 'solo', role: 'attack', duration: 30 });
  await send(client.socket, { kind: 'ready', ready: true });
  const room = server.engine.rooms.get(server.engine.playerView(client.session.id)!.id)!;
  room.deadline = performance.now(); server.engine.advance();
  assert.equal((await send(client.socket, { kind: 'ultimate', roundId: room.roundId, seq: 1 })).code, 'ULTIMATE_CHARGING');
  server.engine.players.get(client.session.id)!.charge = 100;
  assert.equal((await send(client.socket, { kind: 'ultimate', roundId: 'another-round', seq: 2 })).code, 'STALE_ROUND');
  assert.ok((await send(client.socket, { kind: 'ultimate', roundId: room.roundId, seq: 2 })).ok);
  assert.equal((await send(client.socket, { kind: 'ultimate', roundId: room.roundId, seq: 2 })).code, 'STALE_INPUT');
  assert.equal((await post(false)).status, 200);
  const state = await fetch(host + '/api/host/state', { headers: { Cookie: cookie } }).then(r => r.json());
  assert.equal(state.lobby.ultimateMode, false); assert.equal(state.rooms[0].ultimateMode, true);
  assert.equal(state.rooms[0].members[0].ultimate.uses, 1); assert.ok(state.rooms[0].members[0].ultimate.remainingMs > 0);
});
