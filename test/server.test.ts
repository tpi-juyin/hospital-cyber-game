async function connect(url: string, token?: string) { return new Promise<{ socket: Socket; session: SessionView }>((resolve, reject) => { const socket = io(url, { transports: ['websocket'], auth: token ? { token } : {}, reconnection: false }); socket.once('session', session => resolve({ socket, session })); socket.once('connect_error', error => { socket.close(); reject(error); }); }); }
async function send(socket: Socket, action: Action) { return new Promise<Reply>((resolve, reject) => socket.timeout(2000).emit('action', action, (e: Error, r: Reply) => e ? reject(e) : resolve(r))); }
test('host tunnel rebuild aborts rounds, clears credentials, keeps settings and rejects stale/duplicate updates', async t => {
  const requests: number[] = [];
  const server = await startServers({ onRebuildTunnel: generation => { requests.push(generation); } }); t.after(() => server.stop());
  server.engine.defaultDuration = 90; server.engine.allowSurrender = true; server.engine.setUltimateMode(true);
  server.setTunnel('https://old-game.trycloudflare.com', 'ready');
  const host = new URL(server.hostUrl).origin, login = await fetch(server.hostUrl, { redirect: 'manual' });
  const cookie = login.headers.get('set-cookie')!.split(';')[0];
  const post = (kind = 'rebuild-tunnel', auth = true, origin = host) => fetch(host + '/api/host/action', { method: 'POST', headers: { ...(auth ? { Cookie: cookie } : {}), Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ kind, value: true }) });
  const state = () => fetch(host + '/api/host/state', { headers: { Cookie: cookie } }).then(r => r.json());
  const a = await connect(server.playerUrl); t.after(() => a.socket.close());
  await send(a.socket, { kind: 'create', mode: 'solo', role: 'attack', duration: 30, startImmediately: true });
  const room = server.engine.rooms.get(server.engine.playerView(a.session.id)!.id)!;
  room.deadline = performance.now(); server.engine.advance();
  const oldCode = room.code;
  assert.equal((await post('rebuild-tunnel', false)).status, 403);
  assert.equal((await post('rebuild-tunnel', true, 'https://evil.example')).status, 403);
  assert.equal(requests.length, 0); assert.equal(room.phase, 'playing');
  const resetNotice = new Promise<void>(resolve => a.socket.once('hosting-reset', resolve));
  const ended = new Promise<RoomView>(resolve => a.socket.on('room', r => { if (r?.phase === 'ended') resolve(r); }));
  assert.equal((await post()).status, 200); await resetNotice;
  assert.equal((await ended).winner, null); assert.match(room.reason, /不計勝負/);
  assert.equal(server.engine.rooms.size, 0); assert.equal(server.engine.players.size, 0);
  assert.equal((await post()).status, 400); assert.deepEqual(requests, [1]);
  assert.equal((await post('accepting')).status, 400);
  assert.equal((await state()).lobby.joinUrl, ''); assert.equal((await state()).tunnelControl.busy, true);
  await assert.rejects(() => connect(server.playerUrl));
  server.setTunnel('https://old-game.trycloudflare.com', 'late old health', 0, 'ready');
  assert.equal(server.engine.joinUrl, '');
  server.setTunnel('', '模擬失敗', 1, 'failed');
  assert.equal((await state()).tunnelControl.failed, true); assert.equal(server.engine.accepting, false);
  assert.equal((await post()).status, 200); assert.deepEqual(requests, [1, 2]);
  server.setTunnel('https://stale-game.trycloudflare.com', 'late prior attempt', 1, 'ready');
  assert.equal(server.engine.joinUrl, '');
  server.setTunnel('https://new-game.trycloudflare.com', 'ready', 2, 'ready');
  assert.equal(server.engine.accepting, true); assert.equal((await state()).tunnelControl.busy, false);
  await assert.rejects(() => connect(server.playerUrl, a.session.token));
  const b = await connect(server.playerUrl); t.after(() => b.socket.close());
  await send(b.socket, { kind: 'create', mode: 'solo', role: 'defense', duration: 90 });
  assert.notEqual(server.engine.playerView(b.session.id)!.code, oldCode);
  assert.equal(server.engine.defaultDuration, 90); assert.equal(server.engine.allowSurrender, true); assert.equal(server.engine.lobby().ultimateMode, true);
  server.engine.accepting = false;
  await post(); server.setTunnel('https://next-game.trycloudflare.com', 'ready', 3, 'ready');
  assert.equal(server.engine.accepting, false, 'preserve host choice to pause new admission');
});
